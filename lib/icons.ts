/**
 * Every export name in the package. A type-only import, so none of the 13k
 * glyphs this names reach the bundle — it exists purely to type `source`.
 */
type HugeIconName = keyof typeof import("@hugeicons/core-free-icons")

/**
 * The design system's icon vocabulary.
 *
 * `@hugeicons/core-free-icons` ships ~5.4k glyphs under names that describe the
 * drawing (`Tick02Icon`, `Cancel01Icon`), not the job. This file picks the ones
 * the system actually uses and names them by role, so a component asks for
 * `icon.close` rather than remembering which of the eleven `Cancel*` variants
 * the rest of the app settled on. Swapping the underlying glyph is then a
 * one-line change here instead of a repo-wide find-and-replace.
 *
 * Distinct from [icon-sets.ts](lib/icon-sets.ts), which indexes *every* icon in
 * the package for the `/icons` explorer. This is the curated subset.
 *
 * Render entries with [`Icon`](components/icons/icon.tsx):
 *
 * ```tsx
 * <Icon icon={icon.close} size="sm" tone="muted" label="Close" />
 * ```
 */

