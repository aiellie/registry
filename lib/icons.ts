/** Every role name in the catalog. */
export type IconName = keyof typeof iconCatalog

/** A definition with its role name attached — what the lookups below hand back. */
export type IconCatalogEntry = IconDefinition & { name: IconName }

/**
 * Role name → glyph, for the common case where only the drawing is needed:
 *
 * ```tsx
 * <Icon icon={icon.chevronDown} />
 * ```
 */
export const icon = Object.fromEntries(
  Object.entries(iconCatalog).map(([name, def]) => [name, def.icon])
) as Record<IconName, IconSvgElement>

export const iconNames = Object.keys(iconCatalog) as IconName[]

/* -------------------------------------------------------------------------- */
/*                                   Lookups                                   */
/* -------------------------------------------------------------------------- */

/** The full definition — glyph, label, category, keywords. */
export function getIcon(name: IconName): IconDefinition {
  return iconCatalog[name]
}

/** Catalog entries in a category, in declaration order. */
export function getIconsByCategory(
  category: IconCategoryId
): IconCatalogEntry[] {
  return iconNames
    .map((name) => ({ name, ...iconCatalog[name] }))
    .filter((entry) => entry.category === category)
}

export interface IconGroup {
  category: IconCategory
  icons: IconCatalogEntry[]
}

/** The whole catalog grouped, in `iconCategoryOrder`. Empty groups dropped. */
export function getIconGroups(): IconGroup[] {
  return iconCategoryOrder
    .map((id) => ({
      category: iconCategories[id],
      icons: getIconsByCategory(id),
    }))
    .filter((group) => group.icons.length > 0)
}

/**
 * Name, label, and keyword search. Exact name first, then prefix matches, then
 * anything containing the query — enough for a picker over ~150 entries; the
 * 5.4k-icon explorer uses the ranked `searchIcons` in `lib/icon-sets.ts`.
 */
export function searchIconCatalog(query: string): IconCatalogEntry[] {
  const q = query.trim().toLowerCase()
  const entries = iconNames.map((name) => ({ name, ...iconCatalog[name] }))
  if (!q) return entries

  const score = (entry: (typeof entries)[number]) => {
    const name = entry.name.toLowerCase()
    const label = entry.label.toLowerCase()
    if (name === q || label === q) return 0
    if (name.startsWith(q) || label.startsWith(q)) return 1
    if (name.includes(q) || label.includes(q)) return 2
    if (entry.keywords?.some((k) => k.startsWith(q))) return 3
    if (entry.keywords?.some((k) => k.includes(q))) return 4
    return -1
  }

  return entries
    .map((entry) => ({ entry, rank: score(entry) }))
    .filter(({ rank }) => rank >= 0)
    .sort((a, b) => a.rank - b.rank)
    .map(({ entry }) => entry)
}
