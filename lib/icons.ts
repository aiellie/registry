export interface IconDefinition {
  /** The glyph, straight from `@hugeicons/core-free-icons`. */
  icon: IconSvgElement
  /**
   * The export `icon` was imported under. Carried as data so docs and pickers
   * can print the import line without a reverse lookup over 13k exports; the
   * type catches a typo, but keeping it in step with `icon` is on you.
   */
  source: HugeIconName
  /** Human label for pickers, tooltips, and docs. */
  label: string
  category: IconCategoryId
  /** Extra search terms — the words a person types instead of the name. */
  keywords?: string[]
  /**
   * The opposite state, for icons that toggle. `Icon` renders it when
   * `showAlt` is set, so `eye` and `eye-off` are one entry, not two.
   */
  altIcon?: IconSvgElement
  /**
   * Directional glyph that must mirror under `dir="rtl"`. `Icon` turns this
   * into `rtl:rotate-180`; see the RTL rules in CLAUDE.md.
   */
  directional?: boolean
}

